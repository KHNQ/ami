import { useState } from "react";
import { Brain, Plus, Trash2, HelpCircle, Check, X, TrendingUp } from "lucide-react";
import { PageTitle } from "@shared/components/layout/PageTitle.jsx";
import { PageHeader, PageBody } from "../components/AdminLayout.jsx";
import { useAsync } from "@shared/hooks/useAsync.js";
import { useToast } from "@shared/context/ToastContext.jsx";
import { Skeleton } from "@shared/components/ui/Skeleton.jsx";
import { ErrorState } from "@shared/components/ui/ErrorState.jsx";
import { EmptyState } from "@shared/components/ui/EmptyState.jsx";
import { Button } from "@shared/components/ui/Button.jsx";
import { Input } from "@shared/components/ui/Input.jsx";
import { StatusBadge } from "@shared/components/ui/Badge.jsx";
import { BottomSheet } from "@shared/components/ui/BottomSheet.jsx";
import { relativeTime } from "@shared/lib/format.js";
import { adminApi as api } from "../lib/adminApi.js";

// What the assistant knows, and what it does not.
//
// Two panels because they are two halves of one loop. The right-hand list is
// generated by the assistant itself every time it admits it cannot answer
// something, ranked by how often that question is asked -- so instead of
// guessing what to document, staff work down a list the customers wrote.
// Answering a gap creates the entry and closes the gap in one action.

const EMPTY = { question: "", answer: "", tags: "", status: "published" };

export default function KnowledgePage() {
  const { data, loading, error, refetch } = useAsync(() => api.listKnowledge(), []);
  const { data: gapData, refetch: refetchGaps } = useAsync(() => api.listAnswerGaps(), []);
  const toast = useToast();
  const [editing, setEditing] = useState(null);
  const [form, setForm] = useState(EMPTY);
  const [busy, setBusy] = useState(false);

  const entries = data?.entries || [];
  const gaps = gapData?.gaps || [];

  function openNew(prefill = {}) {
    setForm({ ...EMPTY, ...prefill });
    setEditing("new");
  }

  function openEdit(entry) {
    setForm({
      question: entry.question,
      answer: entry.answer,
      tags: (entry.tags || []).join(", "),
      status: entry.status,
      id: entry.id,
    });
    setEditing(entry.id);
  }

  async function save() {
    if (!form.question.trim() || !form.answer.trim()) return;
    setBusy(true);
    try {
      const payload = {
        question: form.question,
        answer: form.answer,
        tags: form.tags.split(",").map((s) => s.trim()).filter(Boolean),
        status: form.status,
        gap_id: form.gap_id,
      };
      if (editing === "new") await api.createKnowledge(payload);
      else await api.updateKnowledge(editing, payload);
      toast.success("The assistant knows this now");
      setEditing(null);
      refetch();
      refetchGaps();
    } catch (err) {
      toast.error(err.message);
    } finally {
      setBusy(false);
    }
  }

  async function remove(entry) {
    try {
      await api.deleteKnowledge(entry.id);
      toast.success("Entry removed");
      refetch();
    } catch (err) {
      toast.error(err.message);
    }
  }

  async function dismissGap(gap) {
    try {
      await api.updateAnswerGap(gap.id, "ignored");
      refetchGaps();
    } catch (err) {
      toast.error(err.message);
    }
  }

  return (
    <>
      <PageTitle title="Admin · Assistant knowledge" />
      <PageHeader
        title="Assistant knowledge"
        description="Answers the assistant gives in your words, and the questions it still cannot answer."
        actions={
          <Button size="sm" onClick={() => openNew()}>
            <Plus size={14} /> New answer
          </Button>
        }
      />

      <PageBody>
        <div className="grid gap-5 lg:grid-cols-[1fr_360px]">
          {/* --- what it knows --- */}
          <section>
            <h2 className="mb-2.5 font-mono text-[10.5px] font-semibold uppercase tracking-[0.16em] text-fg/30">
              Answers ({entries.length})
            </h2>

            {loading && !data && (
              <div className="flex flex-col gap-2.5">
                {Array.from({ length: 3 }).map((_, i) => (
                  <Skeleton key={i} className="h-20" />
                ))}
              </div>
            )}
            {error && <ErrorState error={error} onRetry={refetch} />}
            {data && entries.length === 0 && (
              <EmptyState
                icon={<Brain />}
                title="Nothing written yet"
                description="Add the answers customers keep asking for — lead times, warranty, what's on the demo floor."
              />
            )}

            <div className="flex flex-col gap-2">
              {entries.map((e) => (
                <div key={e.id} className="rounded-xl border border-surface/8 bg-surface/[0.02] p-3.5">
                  <div className="flex items-start justify-between gap-3">
                    <button type="button" onClick={() => openEdit(e)} className="min-w-0 flex-1 text-start">
                      <div className="text-[13.5px] font-bold text-fg">{e.question}</div>
                      <div className="mt-1 line-clamp-2 text-[12px] leading-snug text-fg/50">{e.answer}</div>
                      <div className="mt-1.5 flex items-center gap-2 text-[11px] text-fg/35">
                        <span className="inline-flex items-center gap-1">
                          <TrendingUp size={11} />
                          {/* Zero uses is a signal, not a failure: it usually
                              means the wording does not match how anyone
                              actually asks. */}
                          {e.hit_count === 0 ? "never used yet" : `used ${e.hit_count}×`}
                        </span>
                        <span>· {relativeTime(e.updated_at)}</span>
                      </div>
                    </button>
                    <div className="flex shrink-0 items-center gap-1.5">
                      <StatusBadge status={e.status} />
                      <button
                        type="button"
                        onClick={() => remove(e)}
                        aria-label="Delete"
                        className="flex h-7 w-7 items-center justify-center rounded-lg text-fg/30 hover:bg-rose-500/10 hover:text-rose-500"
                      >
                        <Trash2 size={13} />
                      </button>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </section>

          {/* --- what it doesn't --- */}
          <section>
            <h2 className="mb-2.5 font-mono text-[10.5px] font-semibold uppercase tracking-[0.16em] text-fg/30">
              Unanswered ({gaps.length})
            </h2>

            {gaps.length === 0 ? (
              <div className="rounded-xl border border-surface/8 bg-surface/[0.02] p-5 text-center">
                <Check size={18} className="mx-auto mb-2 text-brand-green" />
                <p className="text-[12.5px] text-fg/45">
                  Nothing outstanding. Questions the assistant can&apos;t answer show up here automatically.
                </p>
              </div>
            ) : (
              <div className="flex flex-col gap-2">
                {gaps.map((g) => (
                  <div key={g.id} className="rounded-xl border border-amber-500/20 bg-amber-500/[0.05] p-3">
                    <div className="flex items-start gap-2">
                      <HelpCircle size={14} className="mt-0.5 shrink-0 text-amber-500" />
                      <div className="min-w-0 flex-1">
                        <p className="text-[12.5px] font-semibold leading-snug text-fg">{g.sample_question}</p>
                        <p className="mt-1 text-[11px] text-fg/40">
                          asked {g.ask_count}× · last {relativeTime(g.last_asked_at)}
                        </p>
                      </div>
                    </div>
                    <div className="mt-2.5 flex gap-1.5">
                      <Button
                        size="sm"
                        className="flex-1"
                        onClick={() => openNew({ question: g.sample_question, gap_id: g.id })}
                      >
                        Answer it
                      </Button>
                      <button
                        type="button"
                        onClick={() => dismissGap(g)}
                        aria-label="Ignore"
                        className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg text-fg/35 hover:bg-surface/8 hover:text-fg"
                      >
                        <X size={14} />
                      </button>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </section>
        </div>
      </PageBody>

      <BottomSheet
        open={Boolean(editing)}
        onClose={() => setEditing(null)}
        title={editing === "new" ? "New answer" : "Edit answer"}
      >
        <div className="flex flex-col gap-2.5">
          <Input
            placeholder="The question, as a customer would ask it"
            value={form.question}
            onChange={(e) => setForm((f) => ({ ...f, question: e.target.value }))}
          />
          <textarea
            rows={6}
            placeholder="The answer, in your own words. The assistant treats this as authoritative and will prefer it over anything inferred from the website."
            value={form.answer}
            onChange={(e) => setForm((f) => ({ ...f, answer: e.target.value }))}
            className="w-full resize-y rounded-xl border border-surface/12 bg-surface/5 px-3 py-2 text-[13px] text-fg outline-none placeholder:text-fg/30 focus:border-brand-green/40"
          />
          <Input
            placeholder="Tags, comma separated — helps it match related wording"
            value={form.tags}
            onChange={(e) => setForm((f) => ({ ...f, tags: e.target.value }))}
          />
          <label className="flex items-center gap-2 text-[13px] text-fg/70">
            <input
              type="checkbox"
              checked={form.status === "published"}
              onChange={(e) => setForm((f) => ({ ...f, status: e.target.checked ? "published" : "draft" }))}
            />
            Live — the assistant may use this
          </label>
          <Button fullWidth loading={busy} onClick={save} disabled={!form.question.trim() || !form.answer.trim()}>
            Save
          </Button>
        </div>
      </BottomSheet>
    </>
  );
}
