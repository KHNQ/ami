export const DEVICE_BY_ID = new Map(DEVICES.map((d) => [d.id, d]));

export function getDevice(id) {
  return DEVICE_BY_ID.get(id) || DEVICES[0];
}

export function categoryCount(catId) {
  if (catId === "all") return DEVICES.length;
  return DEVICES.filter((d) => d.cat === catId).length;
}

