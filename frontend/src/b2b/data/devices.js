// The device catalogue that drives every B2B surface: the shop grid, the
// device detail modal/page, the comparison table, the ROI and lease
// calculators, and the hotspots layered over the printed catalogue.
//
// `shot` is the single genuinely unusual field here. Every machine photo in
// this app comes out of the real Ashkan 2024 catalogue PDF (public/catalog),
// framed at render time with background-size/background-position rather than
// being cropped into 13 separate files -- the page images are already
// downloaded for the catalogue viewer, so reusing them costs nothing and the
// product shots can never drift out of sync with the printed brochure.
// `page` is 1-based to match the page numbers a doctor reads off the PDF.
//
// `sessionPrice` is USD per treatment session and is what the ROI model bills
// against; it is per-device rather than per-category because a cryolipolysis
// session and a body-composition scan are not remotely the same sale.
//
// `slug` is the join key onto the backend product catalogue (see
// lib/mergeProducts.js). It matches `specs.slug` on the API's product rows,
// which is stable across databases -- product ids are generated per
// environment, and names differ in punctuation ("Prime Lase" here,
// "Primelase Excellence" in the brochure), so neither can be the key.
//
// What lives here versus what comes from the API: this file owns the
// *presentation and sales* layer -- catalogue page crops, ROI session
// pricing, indicative euro prices, the trusted-by list. The API owns
// existence, status, stock, description and the product id that a lead or a
// purchase has to reference. Neither is a copy of the other.

