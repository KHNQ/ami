/**
 * CSS for framing one device's photo out of the full catalogue page image.
 *
 * Returns null when a device has no shot in the printed catalogue (Powershape
 * and WOLF aren't in the 2024 edition) so call sites can fall back to the
 * icon tile rather than rendering a random crop of an unrelated page.
 */
export function deviceShotStyle(device) {
  if (!device?.shot) return null;
  const { page, x, y, zoom } = device.shot;
  return {
    backgroundImage: `url(/catalog/pages/page-${String(page).padStart(2, "0")}.jpg)`,
    backgroundSize: `${zoom}% auto`,
    backgroundPosition: `${x}% ${y}%`,
    backgroundRepeat: "no-repeat",
  };
}
